async function loadGuest(linkId) {
  // Read all params from URL (generated by Google Sheet)
  const urlParams = new URLSearchParams(window.location.search);
  const urlName       = urlParams.get('name');
  const urlType       = urlParams.get('type') || 'birthday';   // birthday / diwali / general
  const urlTone       = urlParams.get('tone') || 'formal';     // formal / friendly
  const urlRelation   = urlParams.get('rel')  || 'friend';

  // If URL has name param (real WhatsApp link from Google Sheet)
  if (urlName) {
    currentGuest = {
      name:        urlName,
      invite_type: urlType,
      tone:        urlTone,
      relation:    urlRelation,
      salutation:  buildSalutation(urlName, urlRelation, urlTone),
      script:      buildScript(urlName, urlType, urlTone, urlRelation)
    };
    return currentGuest;
  }

  // Try Supabase (if configured)
  try {
    if (SUPABASE_URL !== 'YOUR_SUPABASE_URL') {
      const { data, error } = await (await supabase.from('guests')).eq('link_id', linkId).select('*');
      if (!error && data && data.length > 0) {
        currentGuest = data[0];
        return currentGuest;
      }
    }
  } catch (e) {
    console.warn('Supabase not configured, using local fallback');
  }

  // Local fallback DB
  currentGuest = LOCAL_GUEST_DB[linkId] || LOCAL_GUEST_DB['guest_001'];
  return currentGuest;
}

// Build salutation based on relation & tone
function buildSalutation(name, relation, tone) {
  if (tone === 'friendly') {
    if (relation === 'uncle') return `Pranam ${name} Ji! 🙏`;
    if (relation === 'auntie') return `Pranam ${name} Ji! ✨`;
    if (relation === 'friend') return `Arre ${name} yaar! 🎉`;
    if (relation === 'colleague') return `Hey ${name}! 👋`;
    return `Hi ${name}! 👋`;
  }
  // formal
  if (relation === 'uncle') return `Pranam ${name} Ji 🙏`;
  if (relation === 'auntie') return `Pranam ${name} Ji ✨`;
  if (relation === 'colleague') return `Hello ${name} 🙏`;
  return `Hey ${name}! 🎉`;
}

