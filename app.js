// ── Speech Synthesis (fallback voice) ──
function speakScript(script) {
  if (!script || !('speechSynthesis' in window)) {
    // No speech available → auto advance after 8 seconds
    setTimeout(() => switchScreen("screen-card"), 8000);
    return;
  }

  window.speechSynthesis.cancel();
  speechSynthUtterance = new SpeechSynthesisUtterance(script);
  speechSynthUtterance.rate   = 0.88;
  speechSynthUtterance.pitch  = 0.85;
  speechSynthUtterance.volume = 1.0;
  speechSynthUtterance.lang   = 'en-IN';

  const setMaleVoice = () => {
    const voices = window.speechSynthesis.getVoices();
    const prefs  = [
      'Google UK English Male', 'Microsoft David', 'Microsoft Mark',
      'Rishi', 'Daniel', 'Aaron', 'Alex', 'Fred',
      'Google US English', 'en-IN-Wavenet-C'
    ];
    let chosen = null;
    for (const p of prefs) {
      chosen = voices.find(v => v.name.includes(p));
      if (chosen) break;
    }
    if (!chosen) chosen = voices.find(v => v.lang.startsWith('en') && !v.name.toLowerCase().includes('female'));
    if (chosen) {
      speechSynthUtterance.voice = chosen;
      console.log('🎙️ Voice:', chosen.name);
    }
  };

  if (window.speechSynthesis.getVoices().length > 0) setMaleVoice();
  else window.speechSynthesis.onvoiceschanged = setMaleVoice;

  speechSynthUtterance.onend = () => {
    clearTimeout(walkSceneTimer);
    setTimeout(() => switchScreen("screen-card"), 1000);
  };

  // If speech doesn't start in 10s → advance anyway
  walkSceneTimer = setTimeout(() => switchScreen("screen-card"), 15000);

  window.speechSynthesis.speak(speechSynthUtterance);
}

